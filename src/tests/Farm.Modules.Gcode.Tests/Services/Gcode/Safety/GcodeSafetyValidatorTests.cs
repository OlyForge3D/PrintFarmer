using System.Security.Cryptography;
using System.Text;
using Farm.Modules.Gcode.Services.Gcode.Safety;
using Farm.Web.Api.Services.Gcode.Safety;
using Xunit;

namespace Farm.Modules.Gcode.Tests.Services.Gcode.Safety;

public sealed class GcodeSafetyValidatorTests
{
    private static readonly GcodeSafetyValidator Validator = new();

    private static readonly GcodeSafetyLimits Limits = new(
        new(250, 280, true),
        new(200, 200, 200, 0, 0, [], []),
        new(100, true, 60, 100, 200, 3000),
        GcodeSafetyPrintLimits.Empty);

    [Fact]
    public void Validate_OrdinaryOrcaMacrosWithoutLiteralInitializationOrShutdown_ReturnsReport()
    {
        const string Program = """
            ; generated by OrcaSlicer
            ; printer_notes = password api_key https://example.invalid C:\profiles\printer.json
            PRINT_START EXTRUDER=220 BED=60
            G90
            M83
            G1 X10 Y10 Z0.2 F1500 E1.2 ; source /home/operator/model.stl
            G1 X20 Y10 E0.4 ; RUN_SHELL_COMMAND is only metadata
            PRINT_END
            """;

        GcodeSafetyResult<GcodeSafetyReport> result = Validate(Program);

        Assert.True(result.IsValid);
        Assert.Empty(result.Problems);
        Assert.Equal(6, result.Value!.CommandCount);
        Assert.Equal(GcodeSafetyCheckpoint.BeforeSendToPrinter, result.Value.Checkpoint);
        Assert.Equal(Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(Program)))
            .ToLowerInvariant(), result.Value.GcodeSha256);
    }

    [Theory]
    [InlineData("G1 X10 Y10 E1 F1500")]
    [InlineData("M104 S200\nG1 X10 Y10 E1 F1500")]
    [InlineData("G28\nG1 X10 Y10 E1 F1500")]
    [InlineData("TURN_OFF_HEATERS\nM84\nG1 X1 Y1\nM17")]
    [InlineData(";PF_SEG_BEGIN\n;PF_SEG_BEGIN\n;PF_SEG_TRANSITION")]
    [InlineData(";PF_SEG_END")]
    [InlineData("TUNING_TOWER COMMAND=SET_PRESSURE_ADVANCE PARAMETER=ADVANCE START=0 FACTOR=.005")]
    [InlineData("SET_PRESSURE_ADVANCE ADVANCE=2.5")]
    [InlineData("M83\nG1 E-15")]
    [InlineData("M82\nG92 E100\nG1 E80")]
    [InlineData("M106 S255\nM107\nCUSTOM_FIRMWARE_MACRO")]
    public void Validate_HistoricalCalibrationPoliciesAreNotOrdinaryFileRequirements_Accepts(string program)
    {
        Assert.True(Validate(program).IsValid);
    }

    [Theory]
    [InlineData("; api_key=example password authorization: bearer client_secret x-worker-key")]
    [InlineData("; https://example.invalid /home/operator/file C:\\profiles\\file \\\\server\\file")]
    [InlineData("; RUN_SHELL_COMMAND CMD=example /bin/sh cmd.exe powershell curl wget nc ssh")]
    [InlineData("G1 X10 Y10 ; S999 F999999 X999 Z999")]
    [InlineData("SET_VELOCITY_LIMIT VELOCITY=100 ; ACCEL=99999")]
    [InlineData("M104 ; S999")]
    [InlineData("M117 password https://example.invalid /home/operator/file C:\\profiles\\file")]
    [InlineData("M117 RUN_SHELL_COMMAND curl /bin/sh")]
    [InlineData("MY_RUN_SHELL_COMMAND_MACRO")]
    [InlineData("PRINT_START FILE=/home/operator/file URL=https://example.invalid API_KEY=example")]
    public void Validate_MetadataCommentsAndMacroArguments_DoNotTriggerSubstringChecks(string program)
    {
        Assert.True(Validate(program).IsValid);
    }

    [Theory]
    [InlineData("RUN_SHELL_COMMAND CMD=example")]
    [InlineData("  run_shell_command\tCMD=example ; comment")]
    [InlineData("RUN_SHELL_COMMAND; ignored")]
    [InlineData("N1 RUN_SHELL_COMMAND CMD=example")]
    [InlineData("N10RUN_SHELL_COMMAND CMD=example")]
    [InlineData("n10run_shell_command CMD=example")]
    [InlineData("/bin/sh example")]
    [InlineData("cmd.exe example")]
    [InlineData("powershell example")]
    [InlineData("curl https://example.invalid")]
    [InlineData("wget https://example.invalid")]
    [InlineData("nc example")]
    [InlineData("ssh example")]
    public void Validate_ExecutableHostCommand_Rejects(string program)
    {
        GcodeSafetyResult<GcodeSafetyReport> result = Validate("; metadata\n" + program);
        GcodeSafetyProblem problem = Assert.Single(result.Problems);
        Assert.False(result.IsValid);
        Assert.Equal(GcodeSafetyProblemCodes.ContainsHostCommand, problem.Code);
        Assert.Equal("gcode.line[2]", problem.Field);
    }

    [Theory]
    [InlineData("M104 S251", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("N1 M104 S251", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("N10M104 S251", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("M109 S251", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("M140 S101", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("M190 S101", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("M141 S61", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("M191 S61", GcodeSafetyProblemCodes.TemperatureAboveLimit)]
    [InlineData("M204 S3001", GcodeSafetyProblemCodes.AccelerationAboveLimit)]
    [InlineData("SET_VELOCITY_LIMIT ACCEL=3001", GcodeSafetyProblemCodes.AccelerationAboveLimit)]
    [InlineData("SET_VELOCITY_LIMIT VELOCITY=201", GcodeSafetyProblemCodes.SpeedAboveLimit)]
    [InlineData("G1 X10 E1 F6060", GcodeSafetyProblemCodes.SpeedAboveLimit)]
    [InlineData("G1 X10 F12060", GcodeSafetyProblemCodes.SpeedAboveLimit)]
    [InlineData("G1 X201", GcodeSafetyProblemCodes.MotionOutsideBuildVolume)]
    [InlineData("G1 Y-1", GcodeSafetyProblemCodes.MotionOutsideBuildVolume)]
    [InlineData("G1 Z201", GcodeSafetyProblemCodes.MotionOutsideBuildVolume)]
    public void Validate_ConfiguredEnvelopeExceeded_Rejects(string command, string code)
    {
        GcodeSafetyResult<GcodeSafetyReport> result = Validate("PRINT_START\n" + command + "\nPRINT_END");
        Assert.False(result.IsValid);
        Assert.Contains(result.Problems, problem => problem.Code == code);
    }

    [Theory]
    [InlineData("M104 S250")]
    [InlineData("M140 S100")]
    [InlineData("M141 S60")]
    [InlineData("M204 S3000")]
    [InlineData("SET_VELOCITY_LIMIT VELOCITY=200 ACCEL=3000")]
    [InlineData("G1 X200 Y200 Z200 E1 F6000")]
    [InlineData("G1 X200 F12000")]
    public void Validate_AtConfiguredCeilings_Accepts(string program)
    {
        Assert.True(Validate(program).IsValid);
    }

    [Fact]
    public void Validate_UnsetNumericLimits_SkipsChecks()
    {
        const string Program = "M104 S999\nM140 S999\nM204 S99999\nG1 X999 Y999 Z999 E1 F99999";
        Assert.True(Validator.Validate(new(GcodeSafetyLimits.Empty, Program,
            GcodeSafetyCheckpoint.BeforeQueueing)).IsValid);
        Assert.False(Validate(Program).IsValid);
    }

    [Fact]
    public void Validate_ChamberHeatingWithoutConfiguredSupport_Rejects()
    {
        Assert.False(Validator.Validate(new(GcodeSafetyLimits.Empty, "M141 S40",
            GcodeSafetyCheckpoint.BeforeQueueing)).IsValid);
        Assert.True(Validator.Validate(new(GcodeSafetyLimits.Empty, "M141 S0",
            GcodeSafetyCheckpoint.BeforeQueueing)).IsValid);
    }

    [Fact]
    public void Validate_PrintablePolygonAndExclusion_RejectsOutsideAndInsideRespectively()
    {
        GcodeSafetyPoint[] polygon = [new(0, 0), new(100, 0), new(0, 100)];
        GcodeSafetyLimits limits = Limits with
        {
            Bed = Limits.Bed with
            {
                PrintablePolygon = polygon,
                ExcludedRegions = [new("clip", [new(5, 5), new(15, 5), new(15, 15), new(5, 15)])],
            },
        };
        Assert.True(Validate("G1 X20 Y20", limits).IsValid);
        Assert.Contains(Validate("G1 X90 Y90", limits).Problems,
            problem => problem.Code == GcodeSafetyProblemCodes.MotionOutsidePrintablePolygon);
        Assert.Contains(Validate("G1 X10 Y10", limits).Problems,
            problem => problem.Code == GcodeSafetyProblemCodes.MotionInsideExcludedRegion);
    }

    [Fact]
    public void Validate_FlowLimitsSupplied_StillRejectsExcessiveFlow()
    {
        GcodeSafetyLimits limits = Limits with { Print = new(1.75m, 5m) };
        Assert.Contains(Validate("M83\nG1 X10 E10 F6000", limits).Problems,
            problem => problem.Code == GcodeSafetyProblemCodes.VolumetricFlowAboveLimit);
        Assert.True(Validate("M83\nG1 X10 E10 F6000").IsValid);
    }

    [Fact]
    public void Validate_EmptyProgram_Rejects()
    {
        Assert.Contains(Validate(string.Empty).Problems,
            problem => problem.Code == GcodeSafetyProblemCodes.Malformed);
    }

    [Fact]
    public void Validate_NullRequest_Throws()
    {
        Assert.Throws<ArgumentNullException>(() => Validator.Validate(null!));
    }

    private static GcodeSafetyResult<GcodeSafetyReport> Validate(string program, GcodeSafetyLimits? limits = null) =>
        Validator.Validate(new(limits ?? Limits, program, GcodeSafetyCheckpoint.BeforeSendToPrinter));
}
