                });
            }, 0, region, region + 1, budget);
        }
    }

    private static byte[] BinaryGcode(string metadata, byte[] image)
    {
        using MemoryStream output = new();
        using BinaryWriter writer = new(output);
        writer.Write("GCDE"u8);
        writer.Write(1u);
        writer.Write((ushort)1);
        writer.Write(BinaryBlock(2, Encoding.UTF8.GetBytes(metadata)));
        writer.Write(BinaryBlock(5, image));
        writer.Write((ushort)1);
        writer.Write((ushort)3);
        writer.Write(uint.MaxValue);
        return output.ToArray();
    }

    // Uncompressed block with a CRC32 trailer, following the little-endian layout of the bgcode specification.
    private static byte[] BinaryBlock(ushort type, byte[] payload)
    {
        using MemoryStream output = new();
        using BinaryWriter writer = new(output);
        writer.Write(type);
        writer.Write((ushort)0);
        writer.Write((uint)payload.Length);
        writer.Write((ushort)0);
        if (type == 5)
        {
            writer.Write((ushort)1);
            writer.Write((ushort)1);
        }

        writer.Write(payload);
        writer.Write(Checksum(output.ToArray()));
        return output.ToArray();
    }

    private static uint Checksum(byte[] bytes)
    {
        uint crc = uint.MaxValue;
        foreach (byte value in bytes)
        {
            crc ^= value;
            for (int bit = 0; bit < 8; bit++)
            {
                crc = (crc & 1) == 0 ? crc >> 1 : (crc >> 1) ^ 0xedb88320;
            }
        }

        return ~crc;
    }

    private sealed class FakeFile(byte[] initial, bool ignoreRange = false)
    {
        private readonly List<CountingStream> streams = [];

        public byte[] Content { get; set; } = initial;

        public List<string> Ranges { get; } = [];

        public Action<int>? BeforeResponse { get; set; }

        public int Length => Content.Length;

        public long StreamBytesRead => streams.Sum(stream => (long)stream.BytesRead);

        public Task<PrinterFileRegion> ReadAsync(
            long offset, int count, long? size, PrinterFileEnrichmentBudget budget) =>
            PrinterFileEnrichmentTransport.ReadRegionAsync((range, _) =>
            {
                budget.BeginRequest();
                BeforeResponse?.Invoke(Ranges.Count);
                Ranges.Add(range.ToString());
                return Task.FromResult(Respond(range));
            }, offset, count, size, budget);

        private HttpResponseMessage Respond(RangeHeaderValue range)
        {
            if (ignoreRange)
            {
                CountingStream stream = new(Content);
                streams.Add(stream);
                HttpResponseMessage whole = new(HttpStatusCode.OK) { Content = new StreamContent(stream) };
                whole.Content.Headers.ContentLength = Content.Length;
                return whole;
            }

            RangeItemHeaderValue item = range.Ranges.Single();
            int from = checked((int)item.From!.Value);
            int to = Math.Min(checked((int)item.To!.Value), Content.Length - 1);
            HttpResponseMessage partial = new(HttpStatusCode.PartialContent)
            {
                Content = new ByteArrayContent(Content[from..(to + 1)]),
            };
            partial.Content.Headers.ContentRange = new(from, to, Content.Length);
            return partial;
        }
    }

    private sealed class CountingStream(byte[] bytes) : MemoryStream(bytes, writable: false)
    {
        public int BytesRead { get; private set; }

        public override bool CanSeek => false;

        public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
        {
            int count = await base.ReadAsync(buffer, cancellationToken);
            BytesRead += count;
            return count;
        }
    }
