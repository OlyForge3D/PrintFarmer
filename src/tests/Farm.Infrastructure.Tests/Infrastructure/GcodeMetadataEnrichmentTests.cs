using System.Text;
using Farm.Infrastructure.Services.Gcode;
using Farm.Infrastructure.Services.Printers;
using Microsoft.Extensions.Logging.Abstractions;

namespace Farm.Infrastructure.Tests.Infrastructure;

public sealed class GcodeMetadataEnrichmentTests
{
    private readonly GcodeMetadataExtractorService _service = new(NullLogger<GcodeMetadataExtractorService>.Instance);
    private const string Thumbnail = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==";

    [Theory]
    [InlineData("", null)]
    [InlineData("invalid", null)]
    [InlineData("-1", null)]
    [InlineData("NaN", null)]
    [InlineData("0", 0.0)]
    public async Task ExtractMetadataAsync_MissingMiddleWeight_PreservesToolIdentityAndUnknownTotal(
        string middle, double? expected)
    {
        GcodeMetadataExtracted result = await _service.ExtractMetadataAsync($"""
            ; filament used [g] = 138.2,{middle},22
            ; filament_colour = #000000;;#FF0000
            ; filament_type = PLA;;PETG
            """);

        Assert.NotNull(result.Tools);
        Assert.Equal([0, 1, 2], result.Tools.Select(tool => tool.Index));
        Assert.Equal([138.2, expected, 22], result.Tools.Select(tool => tool.FilamentUsedG));
        Assert.Equal(["#000000", null, "#FF0000"], result.Tools.Select(tool => tool.Color));
        Assert.Equal(["PLA", null, "PETG"], result.Tools.Select(tool => tool.Material));
        Assert.Equal(expected.HasValue ? 160.2 : null, result.FilamentWeightGrams);
        Assert.Equal(expected.HasValue ? true : null, result.FilamentWeightIsDerived);
        if (!expected.HasValue)
        {
            Assert.Null(result.FilamentPerExtruderWeightG);
        }

        Assert.True(result.ToPrinterPrintMetadata().IsValid());
    }

    [Fact]
    public async Task ExtractMetadataAsync_UnequalArrays_DoesNotInventMissingWeightOrPartialTotal()
    {
        GcodeMetadataExtracted result = await _service.ExtractMetadataAsync("""
            ; filament used [g] = 25.1
            ; filament_type = PA;PLA
            ; filament_colour = #123456;not-a-color
            """);

        Assert.Collection(result.Tools!,
            tool => Assert.Equal(25.1, tool.FilamentUsedG),
            tool =>
            {
                Assert.Null(tool.FilamentUsedG);
                Assert.Null(tool.Color);
                Assert.Equal("PLA", tool.Material);
            });
        Assert.Null(result.FilamentWeightGrams);
        Assert.Null(result.FilamentWeightIsDerived);
    }

    [Fact]
    public async Task ExtractMetadataAsync_ExplicitTotalWithIncompleteTools_PreservesReportedTotal()
    {
        GcodeMetadataExtracted result = await _service.ExtractMetadataAsync("""
            ; filament used [g] = 138.2,,22
            ; total filament used [g] = 165.7
            """);

        Assert.Equal(165.7, result.FilamentWeightGrams);
        Assert.False(result.FilamentWeightIsDerived);
        Assert.Null(result.Tools![1].FilamentUsedG);
        Assert.True(result.ToPrinterPrintMetadata().IsValid());
    }

    [Theory]
    [InlineData("Snapmaker Orca", "2.3.6", "6h", 21600)]
    [InlineData("OrcaSlicer", "2.4.0-alpha", "3h 13m", 11580)]
    [InlineData("PrusaSlicer", "2.9.4+linux-x64", "45s", 45)]
    public void ExtractBoundedMetadata_SourceReportedDetails_PreservesNamesVersionsAndUnits(
        string slicer, string version, string duration, double seconds)
    {
        GcodeMetadataExtractionResult result = _service.ExtractBoundedMetadata($"""
            ; generated by {slicer} {version} on 2026-10-27
            ; estimated printing time (normal mode) = {duration}
            ; layer_height = 0.20
            ; total layers count = 381
            ; nozzle_diameter = 0.4
            ; first_layer_temperature = 220
            ; first_layer_bed_temperature = 65
            ; sparse_infill_density = 15%
            ; sparse_infill_pattern = grid
            ; enable_support = 1
            ; support_type = tree(auto)
            ; support_style = organic
            ; printer_model = Snapmaker U1
            T0
            T1
            ; printing object one
            """, captureThumbnail: false);
        PrinterPrintMetadata metadata = result.Metadata.ToPrinterPrintMetadata();

        Assert.Equal(slicer, metadata.SlicerName);
        Assert.Equal(version, metadata.SlicerVersion);
        Assert.Equal(seconds, metadata.EstimatedPrintTimeSeconds);
        Assert.Equal(0.2, metadata.LayerHeightMm);
        Assert.Equal(381, metadata.LayerCount);
        Assert.Equal(0.4, metadata.NozzleDiameterMm);
        Assert.Equal(220, metadata.NozzleTemperatureC);
        Assert.Equal(65, metadata.BedTemperatureC);
        Assert.Equal(15, metadata.InfillPercentage);
        Assert.Equal("grid", metadata.InfillPattern);
        Assert.True(metadata.SupportEnabled);
        Assert.Equal("tree(auto)", metadata.SupportType);
        Assert.Equal("organic", metadata.SupportStyle);
        Assert.Equal("Snapmaker U1", metadata.PrinterModel);
        Assert.Null(result.Metadata.ToolChangesCount);
        Assert.Null(result.Metadata.ObjectCount);
        Assert.True(metadata.IsValid());
        Assert.True(metadata.FitsStorage());
    }

    [Theory]
    [InlineData("; support_type = tree(auto)")]
    [InlineData("; enable_support = 2")]
    [InlineData("; support_material = false-ish")]
    public void ExtractBoundedMetadata_NoExplicitSupportFlag_RemainsUnknown(string content)
    {
        Assert.Null(_service.ExtractBoundedMetadata(content, false).Metadata.SupportEnabled);
    }

    [Theory]
    [InlineData("9000x1", "image-dimensions")]
    [InlineData("4096x4096", "image-dimensions")]
    public void ExtractBoundedMetadata_ExcessiveImageDimensions_PreservesMetadata(string dimensions, string reason)
    {
        GcodeMetadataExtractionResult result = _service.ExtractBoundedMetadata($"""
            ; layer_height = 0.15
            ; thumbnail begin {dimensions}
            ; {Thumbnail}
            ; thumbnail end
            """, true);

        Assert.Equal(0.15, result.Metadata.LayerHeight);
        Assert.Null(result.Metadata.ThumbnailData);
        Assert.Equal(PrinterFileEnrichmentState.Partial, result.ThumbnailState);
        Assert.Equal(reason, result.ThumbnailReason);
    }

    [Fact]
    public void ExtractBoundedMetadata_CompleteThumbnail_ReturnsExactBytes()
    {
        GcodeMetadataExtractionResult result = _service.ExtractBoundedMetadata($"""
            ; thumbnail begin 1x1
            ; {Thumbnail}
            ; thumbnail end
            """, true);

        Assert.Equal(PrinterFileEnrichmentState.Ready, result.ThumbnailState);
        Assert.Equal(Convert.FromBase64String(Thumbnail), result.Metadata.ThumbnailData);
        Assert.Null(result.ThumbnailReason);
    }

    [Theory]
    [InlineData("; thumbnail begin 1x1\n; bad", "incomplete-thumbnail")]
    [InlineData("; thumbnail begin 1x1\n; !!\n; thumbnail end", "invalid-thumbnail")]
    [InlineData("; thumbnail_SVG begin 1x1\n; AAAA\n; thumbnail_SVG end", "unsupported-thumbnail")]
    public void ExtractBoundedMetadata_IncompleteInvalidOrUnsupportedImage_NeverReportsAbsence(
        string content, string reason)
    {
        GcodeMetadataExtractionResult result = _service.ExtractBoundedMetadata(content, true);

        Assert.Null(result.Metadata.ThumbnailData);
        Assert.Equal(reason, result.ThumbnailReason);
        Assert.NotEqual(PrinterFileEnrichmentState.Absent, result.ThumbnailState);
    }

    [Fact]
    public void ExtractBoundedMetadata_CommentBudget_StopsBeforeUnboundedMetadata()
    {
        string content = new StringBuilder("; layer_height = 0.2\n; ")
            .Append('x', PrinterFileEnrichmentLimits.MetadataBytes)
            .Append("\n; nozzle_diameter = 0.4").ToString();
        GcodeMetadataExtractionResult result = _service.ExtractBoundedMetadata(content, false);

        Assert.Equal("metadata-limit", result.MetadataReason);
        Assert.Equal(0.2, result.Metadata.LayerHeight);
        Assert.Null(result.Metadata.NozzleDiameter);
    }

    [Fact]
    public void ExtractBoundedMetadata_DecodedLimitAndCancellation_ReturnExplicitOutcomeOrCancel()
    {
        GcodeMetadataExtractionResult result = _service.ExtractBoundedMetadata(
            new string('x', PrinterFileEnrichmentLimits.MaximumDecodedBytes + 1), true);
        Assert.Equal("decoded-limit", result.MetadataReason);
        Assert.Null(result.Metadata.ThumbnailData);
        Assert.False(result.Metadata.ToPrinterPrintMetadata().HasValues);
        using CancellationTokenSource cancellation = new();
        cancellation.Cancel();
        Assert.Throws<OperationCanceledException>(() =>
            _service.ExtractBoundedMetadata("; layer_height = 0.2", true, cancellation.Token));
    }
}
