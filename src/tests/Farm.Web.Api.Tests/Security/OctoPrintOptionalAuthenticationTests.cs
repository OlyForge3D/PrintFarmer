    private ApiKey SeedApiKey(bool rawKey = false)
    {
        var key = new ApiKey { UserId = _userId, Purpose = ApiKeyPurpose.OctoPrint, IsActive = true };
        if (rawKey)
        {
            _apiKeys.Setup(repository => repository.GetByRawKeyAsync(ApiKeyValue)).ReturnsAsync(key);
        }
        else
        {
            string hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(ApiKeyValue)));
            _apiKeys.Setup(repository => repository.GetByKeyHashAsync(hash)).ReturnsAsync(key);
        }

        return key;
    }

    private void SetBearer(string? subject, bool grantQueuePermission = true)
    {
        List<Claim> claims = [];
        if (subject is not null)
        {
            claims.Add(new Claim(ClaimTypes.NameIdentifier, subject));
        }

        if (grantQueuePermission)
        {
            claims.Add(new Claim(PrintFarmerPermissions.ClaimType, PrintFarmerPermissions.Queue.Write));
        }

        var token = new JwtSecurityToken(
            issuer: "PrintFarmer",
            audience: "PrintFarmer",
            claims: claims,
            expires: DateTime.UtcNow.AddMinutes(5),
            signingCredentials: new SigningCredentials(
                new SymmetricSecurityKey(Encoding.UTF8.GetBytes(SigningKey)), SecurityAlgorithms.HmacSha256));
        _client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue(
            "Bearer", new JwtSecurityTokenHandler().WriteToken(token));
    }

    private async Task<HttpResponseMessage> UploadAsync(bool print = true)
    {
        using var form = new MultipartFormDataContent();
        using var content = new ByteArrayContent(Encoding.UTF8.GetBytes(Gcode));
        content.Headers.ContentType = new MediaTypeHeaderValue("application/octet-stream");
        form.Add(content, "file", "upload.gcode");
        form.Add(new StringContent(print ? "true" : "false"), "print");
        return await _client.PostAsync($"/api/files/local?printerId={_printerId}", form);
    }

    private void VerifyQueuedActor(Guid? actor)
    {
        _queue.Verify(service => service.AddJobToQueueAsync(
            It.Is<QueuePrintJobDto>(request =>
                request.GcodeFileId == _fileId &&
                request.AssignedPrinterId == _printerId &&
                request.RequiredPrinterModel == "Qidi Plus 4" &&
                request.RequiredNozzleDiameter == 0.4m &&
                request.RequiredMaterialType == "PLA"),
            actor,
            It.IsAny<CancellationToken>()), Times.Once);
    }

    private async Task AssertAuthenticationRejectedAsync(HttpResponseMessage response)
    {
        Assert.Equal(HttpStatusCode.Unauthorized, response.StatusCode);
        using JsonDocument body = JsonDocument.Parse(await response.Content.ReadAsStringAsync());
        Assert.Equal("authentication_required", body.RootElement.GetProperty("code").GetString());
        AssertNoSideEffects();
    }

    private void AssertNoSideEffects()
    {
        Assert.Empty(_files.Invocations);
        Assert.Empty(_queue.Invocations);
    }
