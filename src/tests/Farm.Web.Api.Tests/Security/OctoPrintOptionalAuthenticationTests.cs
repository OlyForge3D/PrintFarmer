    [Fact]
    public async Task Upload_CatalogMetadata_ListsActualRouteAndStillAllowsAnonymousEnqueue()
    {
        using HttpResponseMessage response = await UploadAsync();

        Assert.Equal(HttpStatusCode.Accepted, response.StatusCode);
        VerifyQueuedActor(null);

        DbContextOptions<AppDbContext> options = new DbContextOptionsBuilder<AppDbContext>()
            .UseInMemoryDatabase($"octoprint-permission-catalog-{Guid.NewGuid()}")
            .Options;
        await using var db = new AppDbContext(options);
        var catalogService = new PermissionCatalogService(
            _host.Services.GetRequiredService<EndpointDataSource>(), db);

        PermissionCatalogDto catalog = await catalogService.GetCatalogAsync();

        PermissionResourceGroupDto group = Assert.Single(catalog.Resources, group => group.Resource == "queue");
        PermissionCatalogEntryDto entry = Assert.Single(
            group.Permissions, permission => permission.Permission == PrintFarmerPermissions.Queue.Write);
        Assert.Single(entry.Routes, route => route.Method == "POST" && route.Template == "api/files/local");
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task Upload_OptionalWithoutCredentials_ReturnsFileAndEnqueuesOnlyWhenRequested(bool print)
    {
        using HttpResponseMessage response = await UploadAsync(print);

        Assert.Equal(print ? HttpStatusCode.Accepted : HttpStatusCode.OK, response.StatusCode);
        using JsonDocument body = JsonDocument.Parse(await response.Content.ReadAsStringAsync());
        Assert.Equal(_fileId.ToString(), body.RootElement.GetProperty("file").GetProperty("id").GetString());
        Assert.Equal("upload.gcode", body.RootElement.GetProperty("file").GetProperty("fileName").GetString());
        Assert.Equal(Encoding.UTF8.GetByteCount(Gcode), body.RootElement.GetProperty("file").GetProperty("fileSize").GetInt64());
        Assert.Equal(Gcode, _uploadedContent);
        Assert.Single(_files.Invocations);

        if (print)
        {
            Assert.Equal(_jobId, body.RootElement.GetProperty("jobId").GetGuid());
            Assert.Equal("Queued", body.RootElement.GetProperty("status").GetString());
            Assert.Equal("Test Qidi Plus 4", body.RootElement.GetProperty("assignedPrinter").GetString());
            VerifyQueuedActor(null);
        }
        else
        {
            Assert.False(body.RootElement.TryGetProperty("jobId", out _));
            Assert.Empty(_queue.Invocations);
        }
    }

