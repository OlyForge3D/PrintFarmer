    [Theory]
    [InlineData(false, "invalid")]
    [InlineData(true, "invalid")]
    [InlineData(false, "desktop")]
    [InlineData(true, "desktop")]
    [InlineData(false, "expired")]
    [InlineData(true, "expired")]
    [InlineData(false, "ownerless")]
    [InlineData(true, "ownerless")]
    [InlineData(false, "inactive-owner")]
    [InlineData(true, "inactive-owner")]
    [InlineData(false, "missing-owner")]
    [InlineData(true, "missing-owner")]
    [InlineData(false, "global")]
    [InlineData(true, "global")]
    public async Task Upload_UnusableApiKey_RejectsBeforeSaving(bool requireApiKey, string reason)
    {
        _settings = new OctoPrintSettings { RequireApiKey = requireApiKey };
        ApiKey key = SeedApiKey();
        switch (reason)
        {
            case "invalid":
                _apiKeys.Reset();
                break;
            case "desktop":
                key.Purpose = ApiKeyPurpose.Desktop;
                break;
            case "expired":
                key.ExpiresAt = DateTime.UtcNow.AddMinutes(-1);
                break;
            case "ownerless":
                key.UserId = null;
                break;
            case "inactive-owner":
                _users.Setup(repository => repository.GetUserEntityAsync(_userId, It.IsAny<CancellationToken>()))
                    .ReturnsAsync(new User { Id = _userId, IsActive = false });
                break;
            case "missing-owner":
                _users.Setup(repository => repository.GetUserEntityAsync(_userId, It.IsAny<CancellationToken>()))
                    .ReturnsAsync((User?)null);
                break;
        }

        _client.DefaultRequestHeaders.Add("X-Api-Key", reason == "global" ? GlobalApiKeyValue : ApiKeyValue);

        using HttpResponseMessage response = await UploadAsync();

        await AssertAuthenticationRejectedAsync(response);
    }

