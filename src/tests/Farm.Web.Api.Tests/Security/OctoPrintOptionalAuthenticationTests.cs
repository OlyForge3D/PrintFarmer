    public OctoPrintOptionalAuthenticationTests()
    {
        var settingsService = new Mock<ISettingsService>();
        settingsService.Setup(service => service.Get<OctoPrintSettings>()).Returns(() => _settings);
        _users.Setup(repository => repository.GetUserEntityAsync(_userId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(new User { Id = _userId, Username = "slicer-user", IsActive = true });
        _users.Setup(repository => repository.GetActiveRoleNamesAsync(_userId, It.IsAny<CancellationToken>()))
            .ReturnsAsync([]);
        _users.Setup(repository => repository.GetGrantedPermissionsAsync(_userId, It.IsAny<CancellationToken>()))
            .ReturnsAsync([("queue", "write")]);
        _users.Setup(repository => repository.GetDeniedPermissionsAsync(_userId, It.IsAny<CancellationToken>()))
            .ReturnsAsync([]);
        _rateLimits.Setup(service => service.CheckOctoPrintUploadLimitAsync(
                It.IsAny<string>(), It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(new RateLimitResult(true, 59));
        _files.Setup(service => service.UploadFileAsync(
                null, It.IsAny<IFormFile>(), It.IsAny<IGcodeUploadSettings>(),
                It.IsAny<IGcodeUploadQuotaService>(), It.IsAny<CancellationToken>()))
            .Returns(async (string? _, IFormFile file, IGcodeUploadSettings _, IGcodeUploadQuotaService _, CancellationToken ct) =>
            {
                using var reader = new StreamReader(file.OpenReadStream());
                _uploadedContent = await reader.ReadToEndAsync(ct);
                return new GcodeFileEntryDto(
                    $"{_fileId}.gcode", file.FileName, file.Length, DateTime.UtcNow, false,
                    Id: _fileId.ToString(), RequiredMaterial: "PLA",
                    ExtractedNozzleDiameter: 0.4, ExtractedPrinterModel: "Qidi Plus 4");
            });
        _queue.Setup(service => service.AddJobToQueueAsync(
                It.IsAny<QueuePrintJobDto>(), It.IsAny<Guid?>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(new JobQueuePrintJobDto
            {
                Id = _jobId,
                GcodeFileId = _fileId,
                AssignedPrinterId = _printerId,
                AssignedPrinterName = "Test Qidi Plus 4",
            });

        _host = new HostBuilder().ConfigureWebHost(builder => builder
            .UseTestServer()
            .UseEnvironment("Testing")
            .ConfigureAppConfiguration((_, configuration) => configuration.AddInMemoryCollection(
                new Dictionary<string, string?>
                {
                    ["Jwt:Key"] = SigningKey,
                    ["OctoPrint:GlobalApiKey"] = GlobalApiKeyValue,
                }))
            .ConfigureServices((context, services) =>
            {
                services.AddPrintFarmerAuthentication(context.Configuration, context.HostingEnvironment);
                services.AddSingleton(settingsService.Object);
                services.AddSingleton(_apiKeys.Object);
                services.AddSingleton(_users.Object);
                services.AddScoped<IOctoPrintAuthService, OctoPrintAuthService>();
                services.AddSingleton(_files.Object);
                services.AddSingleton(_queue.Object);
                services.AddSingleton(_rateLimits.Object);
                services.AddSingleton(Mock.Of<IGcodeUploadSettings>());
                services.AddSingleton(Mock.Of<IGcodeUploadQuotaService>());
                // Deliberately stale options: authentication must use live ISettingsService values.
                services.Configure<OctoPrintSettings>(settings => settings.RequireApiKey = true);
                services.AddControllers().AddApplicationPart(typeof(OctoPrintCompatController).Assembly);
            })
            .Configure(app =>
            {
                app.UseRouting();
                app.UseAuthentication();
                app.UseAuthorization();
                app.UseEndpoints(endpoints =>
                {
                    endpoints.MapControllers();
                    endpoints.MapGet("/protected", context => context.Response.WriteAsync("protected"));
                });
            })).Build();
    }

