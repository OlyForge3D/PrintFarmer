    private sealed record Call(string Origin, string PathAndQuery, string? ApiKeyHeader, string? Authorization, string? Range);

    private sealed class FakePrinter(byte[] content) : HttpMessageHandler
    {
        private readonly List<(string Path, CountingStream Stream)> served = [];
        private int downloads;

        public byte[] Content { get; set; } = content;

        public JsonObject? Meta { get; init; }

        // A null array omits the "thumbnails" key, as Moonraker does for a file without any.
        public JsonArray? Thumbnails { get; init; } = new JsonArray(ThumbnailEntry(LargeReference, 300, 300, 4096));

        // Keyed by absolute request path; any other path below the gcodes root answers 404.
        public Dictionary<string, byte[]> Images { get; init; } = new() { [LargeThumbnailPath] = Png };

        public HttpStatusCode? MetadataStatus { get; init; }

        public string? MetadataBody { get; init; }

        public HttpStatusCode? FileStatus { get; init; }

        public bool IgnoreRange { get; init; }

        public string? DownloadRedirect { get; init; }

        public Action<int, JsonObject>? ChangeDetails { get; set; }

        public Action<int>? BeforeDownload { get; set; }

        public Func<HttpRequestMessage, HttpResponseMessage>? Intercept { get; set; }

        public List<Call> Calls { get; } = [];

        public List<string> Paths => [.. Calls.Select(call => call.PathAndQuery)];

        public PrinterFileInventoryEntry Observation => new("gcodes", "folder/part.gcode", Content.Length, ModifiedValue: "1");

        public long BytesRead => served.Sum(entry => (long)entry.Stream.BytesRead);

        public long DownloadBytesRead =>
            served.Where(entry => entry.Path == FilePath).Sum(entry => (long)entry.Stream.BytesRead);

        private int MetadataReads { get; set; }

        public HttpResponseMessage Serve(HttpRequestMessage request)
        {
            string path = request.RequestUri!.AbsolutePath;
            if (path == MetadataPath)
            {
                return MetadataResponse();
            }

            if (path == FilePath)
            {
                return Download(request.Headers.Range);
            }

            if (path.StartsWith(GcodesPrefix, StringComparison.Ordinal))
            {
                return Images.TryGetValue(path, out byte[]? image)
                    ? Body(path, image, HttpStatusCode.OK, "image/png")
                    : new HttpResponseMessage(HttpStatusCode.NotFound);
            }

            throw new InvalidOperationException($"Unexpected request: {request.Method} {request.RequestUri}");
        }

        protected override Task<HttpResponseMessage> SendAsync(
            HttpRequestMessage request, CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            Calls.Add(new(
                request.RequestUri!.GetLeftPart(UriPartial.Authority),
                request.RequestUri.PathAndQuery,
                request.Headers.TryGetValues("X-Api-Key", out IEnumerable<string>? keys) ? Assert.Single(keys) : null,
                request.Headers.Authorization?.Scheme,
                request.Headers.Range?.ToString()));
            return Task.FromResult(Intercept is null ? Serve(request) : Intercept(request));
        }

        private HttpResponseMessage MetadataResponse()
        {
            int read = MetadataReads++;
            if (MetadataStatus is { } status)
            {
                return new HttpResponseMessage(status);
            }

            if (MetadataBody is not null)
            {
                return Body(MetadataPath, Encoding.UTF8.GetBytes(MetadataBody), HttpStatusCode.OK, "application/json");
            }

            JsonObject result = new()
            {
                ["filename"] = "folder/part.gcode",
                ["size"] = Content.Length,
                ["modified"] = 1,
            };
            if (Meta is not null)
            {
                foreach (KeyValuePair<string, JsonNode?> entry in Meta)
                {
                    result[entry.Key] = entry.Value?.DeepClone();
                }
            }

            if (Thumbnails is not null)
            {
                result["thumbnails"] = Thumbnails.DeepClone();
            }

            ChangeDetails?.Invoke(read, result);
            JsonObject root = new() { ["result"] = result };
            return Body(MetadataPath, Encoding.UTF8.GetBytes(root.ToJsonString()), HttpStatusCode.OK, "application/json");
        }

        private HttpResponseMessage Download(RangeHeaderValue? range)
        {
            BeforeDownload?.Invoke(downloads++);
            if (FileStatus is { } status)
            {
                return new HttpResponseMessage(status);
            }

            if (DownloadRedirect is not null)
            {
                HttpResponseMessage redirect = new(HttpStatusCode.Found);
                redirect.Headers.Location = new Uri(DownloadRedirect);
                return redirect;
            }

            if (IgnoreRange || range is null)
            {
                return Body(FilePath, Content, HttpStatusCode.OK, "application/octet-stream");
            }

            RangeItemHeaderValue item = range.Ranges.Single();
            int from = checked((int)item.From!.Value);
            int to = Math.Min(checked((int)item.To!.Value), Content.Length - 1);
            HttpResponseMessage partial = Body(
                FilePath, Content[from..(to + 1)], HttpStatusCode.PartialContent, "application/octet-stream");
            partial.Content.Headers.ContentRange = new(from, to, Content.Length);
            return partial;
        }

        // Every body is served through a counting stream so tests can prove how much was actually consumed.
        private HttpResponseMessage Body(string path, byte[] body, HttpStatusCode status, string mediaType)
        {
            CountingStream stream = new(body);
            served.Add((path, stream));
            StreamContent streamContent = new(stream);
            streamContent.Headers.ContentLength = body.Length;
            streamContent.Headers.ContentType = new(mediaType);
            return new HttpResponseMessage(status) { Content = streamContent };
        }
    }

    private sealed class CountingStream(byte[] bytes) : MemoryStream(bytes, writable: false)
    {
        public int BytesRead { get; private set; }

        public override bool CanSeek => false;

        public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
        {
            int count = await base.ReadAsync(buffer, cancellationToken);
            BytesRead += count;
            return count;
        }
    }
