    [Fact]
    public async Task EnrichFileAsync_DigestChallengeOnEveryRequest_ChargesEveryWireAttemptToTheBudget()
    {
        using FakePrinter printer = new(LargeGcode(LargeHead, LargeTail)) { Meta = PartialMeta() };
        int generation = 0;
        printer.Intercept = request =>
        {
            string nonce = $"nonce-{generation}";
            if (request.Headers.Authorization is { Scheme: "Digest", Parameter: { } parameter } &&
                parameter.Contains($"nonce=\"{nonce}\"", StringComparison.Ordinal))
            {
                HttpResponseMessage served = printer.Serve(request);
                generation++;
                return served;
            }

            // A stale or missing nonce is answered with a fresh challenge, so every request costs two attempts.
            HttpResponseMessage challenge = new(HttpStatusCode.Unauthorized);
            challenge.Headers.WwwAuthenticate.ParseAdd($"Digest realm=\"printer\", nonce=\"{nonce}\", qop=\"auth\"");
            return challenge;
        };

        PrinterFileEnrichmentContent result = await EnrichAsync(printer);

        Assert.Equal(
            [
                DetailsPath, DetailsPath,
                ThumbnailPath, ThumbnailPath,
                DownloadPath, DownloadPath,
                DownloadPath, DownloadPath,
            ],
            printer.Paths);
        Assert.Equal([HeadRange, HeadRange, TailRange, TailRange], DownloadRanges(printer));
        Assert.All(printer.Calls, call => Assert.Equal(ApiKey, call.ApiKeyHeader));
        Assert.All(printer.Calls, call => Assert.Equal(BaseUrl, call.Origin));
        Assert.Equal(PrinterFileEnrichmentState.Ready, result.MetadataState);
        Assert.Equal(PrinterFileEnrichmentState.Ready, result.ThumbnailState);
        Assert.Equal(printer.BytesRead, result.ResponseBytes);
    }

