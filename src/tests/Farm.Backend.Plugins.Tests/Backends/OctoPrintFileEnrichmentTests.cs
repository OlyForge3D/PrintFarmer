    // Filler lines are not comments, so the extractor ignores them; head and tail text are overlaid.
    private static byte[] LargeGcode(string head, string tail)
    {
        byte[] content = new byte[ThreeMiB];
        ReadOnlySpan<byte> filler = "G1 X1 Y1\n"u8;
        for (int index = 0; index < content.Length; index++)
        {
            content[index] = filler[index % filler.Length];
        }

        Encoding.UTF8.GetBytes(head).CopyTo(content, 0);
        byte[] tailBytes = Encoding.UTF8.GetBytes(tail);
        tailBytes.CopyTo(content, content.Length - tailBytes.Length);
        return content;
    }

