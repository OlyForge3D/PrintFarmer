import type { Page } from '@playwright/test';
import { API_BASE_URL, dismissTourIfVisible, getStoredAuthToken } from '../fixtures/emulator-setup';
import {
  test,
  expect,
  MOONRAKER_PRINTERS,
  MOONRAKER_FILES,
  getPrinterCardByName,
  openPrinterFiles,
  getPrinterFileRow,
  createMoonrakerControl,
  uploadScratchGcodeFile,
  deleteScratchGcodeFile,
  getMoonrakerEmulatorUrl,
} from '../fixtures/moonraker';

const SORT_SCRATCH_FILE = 'aaa-e2e-sort-scratch.gcode';
const DELETE_SCRATCH_FILE = 'e2e-delete-scratch.gcode';

async function openFileCatalog(page: Page, printerId: string) {
  const token = await getStoredAuthToken(page);
  expect(token, 'The printer-file catalog requires an authenticated administrator').toBeTruthy();
  const refresh = await page.request.post(
    `${API_BASE_URL}/api/printer-files/printers/${printerId}/refresh?force=true`,
    { headers: { Authorization: `Bearer ${token}` } },
  );
  expect(refresh.ok(), `Printer-file scan returned ${refresh.status()}: ${await refresh.text()}`).toBe(true);
  await page.evaluate(() => localStorage.setItem('printfarmer-printer-files-viewmode', 'explorer'));
  await page.goto(`/files?source=printers&printer=${printerId}`);
  const catalog = page.getByRole('region', { name: 'On printers', exact: true });
  await expect(catalog.getByRole('table', { name: 'Files on printers' })).toBeVisible();
  return catalog;
}

/**
 * Printer Files E2E Tests — Moonraker emulator-backed.
 *
 * `benchy.gcode` is confirmed (see `fixtures/moonraker.ts`) to be the one
 * live virtual file seeded on every scenario printer — `calibration_cube.gcode`
 * only appears as a history entry's filename, not a live file, so it is not
 * asserted here. These tests assert the real file list content and the
 * delete flow — a missing file, a missing action button, or a silently
 * accepted empty list all fail the test rather than falling back to "some
 * files or an empty state".
 */

test.describe('Printer Files — Moonraker', () => {
  test.describe.configure({ mode: 'serial' });

  test.beforeEach(async ({ page, request }) => {
    await createMoonrakerControl(request).resetAll();
    await deleteScratchGcodeFile(request, 'ready', SORT_SCRATCH_FILE, true);
    await deleteScratchGcodeFile(request, 'ready', DELETE_SCRATCH_FILE, true);
    await page.goto('/printers');
    await expect(getPrinterCardByName(page, MOONRAKER_PRINTERS.ready)).toBeVisible({ timeout: 15_000 });
    await dismissTourIfVisible(page);
  });

  test.afterEach(async ({ request }) => {
    await deleteScratchGcodeFile(request, 'ready', SORT_SCRATCH_FILE, true);
    await deleteScratchGcodeFile(request, 'ready', DELETE_SCRATCH_FILE, true);
    await createMoonrakerControl(request).resetAll();
  });

  test('lists benchy.gcode with legacy read actions and catalog-only deletion', async ({ page }) => {
    const filesDialog = await openPrinterFiles(page, MOONRAKER_PRINTERS.ready);

    const row = getPrinterFileRow(filesDialog, MOONRAKER_FILES.benchy);
    await expect(row, `expected seeded file "${MOONRAKER_FILES.benchy}" to be listed`).toBeVisible();
    await expect(row.getByRole('button', { name: 'Queue for printing' })).toBeEnabled();
    await expect(row.getByRole('button', { name: 'Download file' })).toBeEnabled();
    await expect(row.getByRole('button', { name: 'Delete requires the printer-file catalog' })).toBeDisabled();
  });

  test('downloads seeded G-code through both the legacy and authoritative catalog endpoints', async ({ page, moonrakerSeedReady }) => {
    const filesDialog = await openPrinterFiles(page, MOONRAKER_PRINTERS.ready);
    const row = getPrinterFileRow(filesDialog, MOONRAKER_FILES.benchy);

    const [response, download] = await Promise.all([
      page.waitForResponse((candidate) =>
        candidate.request().method() === 'GET'
        && candidate.url().includes('/files/download?filename=benchy.gcode')),
      page.waitForEvent('download'),
      row.getByRole('button', { name: 'Download file' }).click(),
    ]);

    expect(response.status()).toBe(200);
    expect((await response.body()).toString('utf8')).toContain(
      '; generated by the PrintFarmer Moonraker emulator',
    );
    expect(download.suggestedFilename()).toBe(MOONRAKER_FILES.benchy);

    const printer = moonrakerSeedReady.get(MOONRAKER_PRINTERS.ready)!;
    const catalog = await openFileCatalog(page, printer.id);
    const catalogRow = catalog.getByRole('row').filter({ hasText: MOONRAKER_FILES.benchy });
    const [catalogResponse, catalogDownload] = await Promise.all([
      page.waitForResponse(candidate =>
        candidate.request().method() === 'GET'
        && new URL(candidate.url()).pathname.startsWith('/api/printer-files/')
        && new URL(candidate.url()).pathname.endsWith('/download')),
      page.waitForEvent('download'),
      catalogRow.getByRole('button', { name: 'Download', exact: true }).click(),
    ]);
    expect(catalogResponse.status()).toBe(200);
    expect((await catalogResponse.body()).toString('utf8')).toContain(
      '; generated by the PrintFarmer Moonraker emulator',
    );
    expect(catalogDownload.suggestedFilename()).toBe(MOONRAKER_FILES.benchy);
  });

  test('sorting toggles the visible file order once a second file exists', async ({ page, request }) => {
    // The seed only guarantees one live file; upload a throwaway second file
    // (never touching the guaranteed benchy.gcode) so sort order is actually
    // observable, then clean it up.
    await uploadScratchGcodeFile(request, 'ready', SORT_SCRATCH_FILE);

    const filesDialog = await openPrinterFiles(page, MOONRAKER_PRINTERS.ready);
    const rowLocator = filesDialog.locator('div.group');
    await expect(rowLocator).toHaveCount(2);

    const initialOrder = await rowLocator.allTextContents();
    await filesDialog.getByRole('button', { name: 'Sort direction: ascending', exact: true }).click();
    await expect(filesDialog.getByRole('button', { name: 'Sort direction: descending', exact: true })).toBeVisible();
    await expect.poll(() => rowLocator.allTextContents()).toEqual([...initialOrder].reverse());

    await deleteScratchGcodeFile(request, 'ready', SORT_SCRATCH_FILE);
  });

  test('can delete an uploaded file without touching the guaranteed benchy.gcode seed file', async ({ page, request, moonrakerSeedReady }) => {
    // Delete an uploaded scratch file so the assertion exercises mutation
    // without removing the canonical benchy fixture during the test.
    await uploadScratchGcodeFile(request, 'ready', DELETE_SCRATCH_FILE);

    const printer = moonrakerSeedReady.get(MOONRAKER_PRINTERS.ready)!;
    const catalog = await openFileCatalog(page, printer.id);
    const row = catalog.getByRole('row').filter({ hasText: DELETE_SCRATCH_FILE });
    await expect(row).toBeVisible();
    await row.getByRole('button', { name: 'Delete from printer' }).click();

    const confirmDialog = page.getByRole('dialog', { name: 'Prepare remote delete' });
    await expect(confirmDialog).toBeVisible();
    await expect(confirmDialog).toContainText(DELETE_SCRATCH_FILE);
    await confirmDialog.getByRole('button', { name: 'Review exact delete' }).click();
    const operation = catalog.getByRole('region', { name: 'Remote delete - exact source only' });
    await expect(operation).toContainText(DELETE_SCRATCH_FILE);
    const confirm = operation.getByRole('button', { name: 'Confirm irreversible delete' });
    await expect(confirm).toBeDisabled();
    await operation.getByLabel('I accept irreversible deletion of this exact source without an automatic backup').check();
    await operation.getByLabel('I accept the current-path replacement race for this exact delete').check();
    await expect(confirm).toBeEnabled();
    await confirm.click();
    await expect(operation).toContainText('Deleted - Acknowledged', { timeout: 15_000 });

    const files = await request.get(`${getMoonrakerEmulatorUrl('ready')}/server/files/list?root=gcodes`);
    expect(files.ok()).toBe(true);
    const payload = await files.json() as { result: Array<{ path: string }> };
    expect(payload.result.map(file => file.path)).not.toContain(DELETE_SCRATCH_FILE);
    expect(payload.result.map(file => file.path)).toContain(MOONRAKER_FILES.benchy);
    await expect(catalog.getByRole('row').filter({ hasText: MOONRAKER_FILES.benchy })).toBeVisible();
  });
});
