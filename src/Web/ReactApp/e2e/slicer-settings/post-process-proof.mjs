import { appendFileSync, readFileSync, realpathSync } from 'node:fs';
import { isAbsolute, relative } from 'node:path';

const root = process.env.PF_SETTINGS_RUN_ROOT;
const file = process.argv[2];
if (!root || !file || process.argv.length !== 3) {
  throw new Error('The proof script requires exactly one G-code file and the private test root');
}
const path = realpathSync(file);
const withinRoot = relative(realpathSync(root), path);
if (isAbsolute(withinRoot) || withinRoot === '..' || withinRoot.startsWith('..\\') || withinRoot.startsWith('../')) {
  throw new Error('Refusing to post-process a file outside this test run');
}
const gcode = readFileSync(path, 'utf8');
if (!/^; generated by OrcaSlicer 2\.4\.2 on /m.test(gcode) || !gcode.includes('; CONFIG_BLOCK_END')) {
  throw new Error('Refusing to post-process a file without complete Orca 2.4.2 evidence');
}
appendFileSync(path, '\n; settings-regression-post-process-proof\n');
