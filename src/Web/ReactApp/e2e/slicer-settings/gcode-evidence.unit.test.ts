import { describe, expect, it } from 'vitest';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { assertChangedConfig, assertCommandEvidence, assertComplete, canonical, canonicalConfig, definition, engineConfigKey, inventory, numericMutationStep, parseConfig } from './gcode-evidence';

function gcode(body: string) {
  return `; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2 on 2026-11-01\n; HEADER_BLOCK_END\n; CONFIG_BLOCK_START\n${body}\n; CONFIG_BLOCK_END\n`;
}

describe('settings G-code evidence (not a live slicer test)', () => {
  it.each([
    ['compatible_prints_condition', 'compatible_process_expression_group', '"layer_height < 0.3"', '"layer_height < 0.4"', 'layer_height < 0.4'],
    ['compatible_printers_condition', 'compatible_machine_expression_group', '"";"nozzle_diameter[0] == 0.4";""', '"";"nozzle_diameter[0] > 0";""', 'nozzle_diameter[0] > 0'],
  ])('audits the single-filament engine mapping for %s without accepting scalar coincidences', (key, mapped, before, after, requested) => {
    const setting = definition('filament', key);
    const baseline = new Map([[mapped, before], [key, 'unrelated scalar']]);
    const actual = new Map([[mapped, after], [key, requested]]);
    expect(engineConfigKey('filament', key)).toBe(mapped);
    expect(engineConfigKey('process', key)).toBe(key);
    expect(canonicalConfig(after, setting, 'filament')).toBe(canonical(requested, setting));
    expect(() => assertChangedConfig(setting, requested, baseline, actual, 'filament')).not.toThrow();
    expect(() => assertChangedConfig(setting, requested, baseline, baseline, 'filament')).toThrow('remained unchanged');
    expect(() => assertChangedConfig(setting, 'wrong expression', baseline, actual, 'filament')).toThrow('does not match');
    expect(() => assertChangedConfig(setting, requested, baseline, new Map([[key, requested]]), 'filament')).toThrow('dropped this key');
    expect(() => assertChangedConfig(setting, requested, new Map([[key, before]]), actual, 'filament')).toThrow('baseline CONFIG_BLOCK');
    for (const invalid of ['', `${after};""`, after.split(';').slice(1).join(';')]) {
      expect(() => assertChangedConfig(setting, requested, baseline, new Map([[mapped, invalid]]), 'filament')).toThrow('expression-group entries');
    }
    if (key === 'compatible_printers_condition') {
      expect(() => assertChangedConfig(setting, requested, baseline,
        new Map([[mapped, `"${requested}";"";""`]]), 'filament')).toThrow('does not match');
    }
  });
  it('chooses mutations that survive six-significant-digit float serialization', () => {
    const setting = definition('process', 'inner_wall_acceleration');
    for (const current of [0, 0.2, 100, 10000, 100000, -10000]) {
      const step = numericMutationStep(current, setting);
      const emitted = Number((current + step).toPrecision(6));
      expect(emitted).not.toBe(current);
      expect(emitted).toBe(Number((current + step).toFixed(5)));
    }
    expect(numericMutationStep(10000, { ...setting, type: 'int' })).toBe(1);
    expect(() => numericMutationStep(NaN, setting)).toThrow('not finite');
  });
  it('limits the executable post-processing fixture to complete G-code inside its private run', () => {
    const root = mkdtempSync(join(tmpdir(), 'pf-post-process-proof-'));
    try {
      const owned = join(root, 'owned');
      mkdirSync(owned);
      const file = join(owned, 'proof.gcode');
      const script = join(import.meta.dirname, 'post-process-proof.mjs');
      const run = (path: string) => spawnSync(process.execPath, [script, path], {
        env: { ...process.env, PF_SETTINGS_RUN_ROOT: owned }, encoding: 'utf8',
      });
      writeFileSync(file, gcode('; layer_height = 0.2'));
      expect(run(file).status).toBe(0);
      expect(readFileSync(file, 'utf8')).toContain('\n; settings-regression-post-process-proof\n');
      writeFileSync(file, gcode('; layer_height = 0.2').replace('2.4.2 on', '2.4.2-beta on'));
      expect(run(file).status).toBe(1);
      const outside = join(root, 'outside.gcode');
      writeFileSync(outside, gcode('; layer_height = 0.2'));
      expect(run(outside).status).toBe(1);
      expect(readFileSync(outside, 'utf8')).not.toContain('post-process-proof');
      writeFileSync(file, 'not complete Orca evidence');
      expect(run(file).status).toBe(1);
      expect(readFileSync(file, 'utf8')).toBe('not complete Orca evidence');
    } finally {
      rmSync(root, { recursive: true });
    }
  });
  it('requires actual motion and heater commands rather than accepting config comments as behavior', () => {
    const motion = '; Z_HEIGHT: 0.2\n' + [0.2, 0.42, 0.64, 0.86, 1.08]
      .map(z => `G1 Z${z}\nG1 X1 Y2 E.1`).join('\n');
    expect(assertCommandEvidence('layer_height', 0.22, motion)).toBe(true);
    expect(() => assertCommandEvidence('layer_height', 0.2, motion)).toThrow('actual extrusion');
    expect(() => assertCommandEvidence('layer_height', 0.2, '; layer_height = 0.2')).toThrow('No layer');
    expect(assertCommandEvidence('nozzle_temperature', 221, 'M104 S221\n', 'M104 S220\n')).toBe(true);
    expect(() => assertCommandEvidence('nozzle_temperature', 221, '; nozzle_temperature = 221', 'M104 S220\n')).toThrow('no actual heater');
    expect(() => assertCommandEvidence('nozzle_temperature_initial_layer', 221, 'M104 S221\nM109 S220\n', 'M104 S221\nM109 S220\n'))
      .toThrow('baseline heating phase');
    expect(() => assertCommandEvidence('nozzle_temperature', 221, 'M104 S221\n')).toThrow('baseline heater commands');
  });
  it('inventories both registries without treating pending settings as passing', () => {
    const rows = inventory();
    expect(rows.filter(row => row.profile === 'process')).toHaveLength(343);
    expect(rows.filter(row => row.profile === 'filament')).toHaveLength(98);
    expect(() => assertComplete(rows)).toThrow('441 settings unresolved');
    expect(() => assertComplete(rows.slice(1))).toThrow('inventory differs');
    expect(() => assertComplete([...rows, rows[0]])).toThrow('inventory differs');
    rows[0].status = 'config-verified';
    expect(() => assertComplete(rows)).toThrow('no complete fresh-job evidence');
  });

  it('compares booleans, numbers, intrinsic percentages and vectors by their real type', () => {
    const bool = definition('process', 'enable_support');
    expect(canonical(true, bool)).toBe(canonical('1', bool));
    const layer = definition('process', 'layer_height');
    expect(canonical('0.2200', layer)).toBe(canonical(0.22, layer));
    const percent = definition('process', 'sparse_infill_density');
    expect(canonical('31%', percent)).toBe(canonical(31, percent));
    const vector = { ...layer, coType: 'coFloats' };
    expect(canonical(['0.22', '0.24'], vector)).toBe(canonical('0.22,0.24', vector));
    expect(canonical('0.22,0.24', vector)).not.toBe(canonical('0.24,0.22', vector));
  });

  it('does not erase units, enum case, scripts, invalid values or vector cardinality', () => {
    const mixed = { ...definition('process', 'layer_height'), type: 'float_or_percent' };
    expect(canonical('25%', mixed)).not.toBe(canonical('25', mixed));
    expect(canonical('grid', { ...mixed, type: 'enum' })).not.toBe(canonical('Grid', { ...mixed, type: 'enum' }));
    expect(() => canonical('NaN', mixed)).toThrow('invalid numeric');
    expect(() => canonical('2', definition('process', 'enable_support'))).toThrow('invalid boolean');
    expect(() => canonical([0.2], definition('process', 'layer_height'))).toThrow('array supplied for scalar');
    const strings = { ...mixed, type: 'string', coType: 'coStrings' };
    expect(canonical(['PLA', 'PETG'], strings)).not.toBe(canonical(['PLA'], strings));
    expect(canonicalConfig('"quoted;value"', strings)).toBe(canonical(['quoted;value'], strings));
    expect(canonicalConfig('PLA;PETG', strings)).not.toBe(canonical(['PLA;PETG'], strings));
  });

  it('decodes only documented Orca string escaping while preserving scripts and vector cardinality', () => {
    const scripts = definition('filament', 'filament_start_gcode');
    const script = '; proof "quoted"\nM104 S221\n; C:\\fixture';
    const encoded = '"; proof \\"quoted\\"\\nM104 S221\\n; C:\\\\fixture"';
    expect(canonicalConfig(encoded, scripts)).toBe(canonical([script], scripts));
    expect(canonicalConfig(`${encoded};""`, scripts)).not.toBe(canonical([script], scripts));
    expect(() => canonicalConfig('"unterminated', scripts)).toThrow('Malformed');
    expect(() => canonicalConfig('"bad\\q"', scripts)).toThrow('Unsupported');
    const scalar = definition('process', 'process_change_extrusion_role_gcode');
    expect(canonicalConfig('; proof\\nM400', scalar)).toBe(canonical('; proof\nM400', scalar));
    const baseline = new Map([[scripts.key, '""']]);
    const actual = new Map([[scripts.key, encoded]]);
    expect(() => assertChangedConfig(scripts, [script], baseline, actual)).not.toThrow();
    expect(() => assertChangedConfig(scripts, [script.replace('221', '222')], baseline, actual)).toThrow('does not match');
  });

  it('requires an exact engine identity and a unique nonempty config block', () => {
    expect(() => parseConfig(gcode('; layer_height = 0.2'), '2.3.1')).toThrow('exact OrcaSlicer');
    for (const suffix of ['-beta', '-rc1', '.1', '+custom']) {
      expect(() => parseConfig(gcode('; layer_height = 0.2').replace('2.4.2 on', `2.4.2${suffix} on`), '2.4.2'))
        .toThrow('exact OrcaSlicer');
    }
    expect(() => parseConfig(gcode('; layer_height = 0.2\n; layer_height = 0.3'), '2.4.2')).toThrow('Duplicate');
    expect(parseConfig(gcode('; wipe_tower_x = 15.000\n; wipe_tower_x = 15'), '2.4.2').get('wipe_tower_x')).toBe('15.000');
    expect(() => parseConfig(gcode('; wipe_tower_x = 15.000\n; wipe_tower_x = 16'), '2.4.2')).toThrow('Duplicate');
    expect(() => parseConfig(gcode(''), '2.4.2')).toThrow('Empty');
    expect(() => parseConfig(gcode('; layer_height = 0.2') + '; CONFIG_BLOCK_START\n', '2.4.2')).toThrow('exactly one');
  });

  it('audits the flow-compensation editor vector without relaxing other string vectors', () => {
    const setting = definition('process', 'small_area_infill_flow_compensation_model');
    const requested = '0,0;0.5,0.6;10,1;';
    expect(canonical(requested, setting)).toBe(canonical(['0,0', '0.5,0.6', '10,1', ''], setting));
    const baseline = new Map([[setting.key, '0,0;0.5,0.7;10,1;']]);
    const actual = new Map([[setting.key, requested]]);
    expect(() => assertChangedConfig(setting, requested, baseline, actual)).not.toThrow();
    for (const changed of ['0,0;0.5,0.8;10,1;', '0,0;10,1;', '0,0;0.5,0.6;10,1', `${requested};`]) {
      expect(() => assertChangedConfig(setting, requested, baseline, new Map([[setting.key, changed]]))).toThrow();
    }
    const scripts = definition('filament', 'filament_start_gcode');
    expect(canonical('; proof; M400', scripts)).toBe(canonical(['; proof; M400'], scripts));
  });

  it('negative controls reject missing, lost, altered and baseline-equal changes', () => {
    const setting = definition('process', 'layer_height');
    const baseline = parseConfig(gcode('; layer_height = 0.2'), '2.4.2');
    const changed = parseConfig(gcode('; layer_height = 0.22'), '2.4.2');
    expect(() => assertChangedConfig(setting, 0.22, baseline, changed)).not.toThrow();
    expect(() => assertChangedConfig(setting, 0.22, baseline, baseline)).toThrow('remained unchanged');
    expect(() => assertChangedConfig(setting, 0.2, baseline, changed)).toThrow('did not change');
    expect(() => assertChangedConfig(setting, 0.24, baseline, changed)).toThrow('does not match');
    const dropped = new Map(changed);
    dropped.delete('layer_height');
    expect(() => assertChangedConfig(setting, 0.22, baseline, dropped)).toThrow('dropped this key');
    expect(() => assertChangedConfig(setting, 0.22, new Map(), changed)).toThrow('baseline CONFIG_BLOCK');
  });
});
