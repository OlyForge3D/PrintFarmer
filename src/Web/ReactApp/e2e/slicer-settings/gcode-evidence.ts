import metadata from '../../src/features/slicer/generated/orcaSettingsMetadata.json' with { type: 'json' };

export type ProfileKind = 'process' | 'filament';
export interface SettingDefinition {
  key: string;
  type: string;
  coType: string;
  label: string;
  tooltip?: string;
  mode?: string;
  min?: number;
  max?: number;
}

export interface CoverageRow {
  profile: ProfileKind;
  key: string;
  type: string;
  status: 'unresolved' | 'excluded' | 'config-verified';
  reason: string;
  requested?: unknown;
  baseline?: string;
  baselineRequested?: unknown;
  baselineJobId?: string;
  baselineArtifact?: string;
  dependencies?: Record<string, unknown>;
  emitted?: string;
  jobId?: string;
  attempted: boolean;
  gcodeGenerated: boolean;
  behaviorVerified: boolean;
}

export function inventory(): CoverageRow[] {
  return (['process', 'filament'] as const).flatMap(profile =>
    Object.entries(metadata[profile].settings).map(([key, setting]) => ({
      profile,
      key,
      type: setting.type,
      status: 'unresolved' as const,
      reason: 'Not executed. Registry presence is not G-code evidence.',
      attempted: false,
      gcodeGenerated: false,
      behaviorVerified: false,
    })),
  );
}

export function definition(profile: ProfileKind, key: string): SettingDefinition {
  const settings: Record<string, SettingDefinition> = metadata[profile].settings;
  const result = settings[key];
  if (!result) throw new Error(`Unclassified registry key: ${profile}.${key}`);
  return result;
}

export function parseConfig(gcode: string, version: string): Map<string, string> {
  if (!new RegExp(`^; generated by OrcaSlicer ${version.replaceAll('.', '\\.')} on `, 'm').test(gcode)) {
    throw new Error(`New G-code must identify the exact OrcaSlicer ${version} engine`);
  }
  const starts = [...gcode.matchAll(/^;\s*CONFIG_BLOCK_START\s*$/gm)];
  const ends = [...gcode.matchAll(/^;\s*CONFIG_BLOCK_END\s*$/gm)];
  if (starts.length !== 1 || ends.length !== 1 || starts[0].index >= ends[0].index) {
    throw new Error('Expected exactly one complete CONFIG_BLOCK');
  }
  const config = new Map<string, string>();
  const block = gcode.slice(starts[0].index, ends[0].index);
  for (const line of block.split(/\r?\n/)) {
    const match = /^;\s*(\w+)\s*=\s?(.*)$/.exec(line);
    if (!match) continue;
    if (config.has(match[1])) {
      // Orca 2.4.2 emits both plate and global coordinates (15.000/15).
      // Accept only those two known keys when their numeric values agree.
      const previous = config.get(match[1])!;
      if (['wipe_tower_x', 'wipe_tower_y'].includes(match[1])
        && /^\d+(?:\.\d+)?$/.test(previous) && /^\d+(?:\.\d+)?$/.test(match[2])
        && Number(previous) === Number(match[2])) continue;
      throw new Error(`Duplicate CONFIG_BLOCK key: ${match[1]}`);
    }
    config.set(match[1], match[2]);
  }
  if (config.size === 0) throw new Error('Empty CONFIG_BLOCK');
  return config;
}

function atom(value: unknown, setting: SettingDefinition): unknown {
  const text = String(value).trim();
  if (setting.type === 'bool') {
    if (text === '1' || text === 'true') return true;
    if (text === '0' || text === 'false') return false;
    throw new Error(`${setting.key}: invalid boolean ${text}`);
  }
  if (['int', 'float', 'percent', 'float_or_percent'].includes(setting.type)) {
    if (!/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?%?$/.test(text)) {
      throw new Error(`${setting.key}: invalid numeric value ${text}`);
    }
    const percent = text.endsWith('%');
    const numeric = Number(percent ? text.slice(0, -1) : text);
    if (!Number.isFinite(numeric) || (setting.type === 'int' && !Number.isInteger(numeric))) {
      throw new Error(`${setting.key}: invalid ${setting.type} value ${text}`);
    }
    if (percent && !['percent', 'float_or_percent'].includes(setting.type)) {
      throw new Error(`${setting.key}: unexpected percent unit`);
    }
    // Orca's percent type is intrinsically percent. FloatOrPercent is not:
    // 25 mm and 25% must never compare equal.
    return [numeric, setting.type === 'percent' || percent ? '%' : 'absolute'];
  }
  return String(value);
}

// Orca v2.4.2 src/libslic3r/Config.cpp: escape_string_cstyle and
// escape_strings_cstyle. Only the engine's four emitted escapes are accepted.
function decodeString(value: string): string {
  return value.replace(/\\(.)|\\$/g, (_, char?: string) => {
    if (char === undefined || !['n', 'r', '"', '\\'].includes(char)) throw new Error('Unsupported Orca string escape');
    return char === 'n' ? '\n' : char === 'r' ? '\r' : char;
  });
}

function decodeStrings(value: string): string[] {
  if (value === '') return [];
  const result: string[] = [];
  let rest = value;
  for (;;) {
    rest = rest.replace(/^[ \t]+/, '');
    if (rest.startsWith('"')) {
      const match = /^"((?:[^"\\]|\\.)*)"[ \t]*(;|$)/.exec(rest);
      if (!match) throw new Error('Malformed Orca quoted string vector');
      result.push(decodeString(match[1]));
      rest = rest.slice(match[0].length);
      if (!match[2]) break;
    } else {
      const end = rest.indexOf(';');
      result.push(end < 0 ? rest : rest.slice(0, end));
      if (end < 0) break;
      rest = rest.slice(end + 1);
    }
    if (rest === '') {
      result.push('');
      break;
    }
  }
  return result;
}

export function canonical(value: unknown, setting: SettingDefinition): string {
  const arrayType = ['coBools', 'coInts', 'coFloats', 'coPercents', 'coFloatsOrPercents', 'coStrings', 'coEnums']
    .includes(setting.coType);
  let values: unknown[];
  if (Array.isArray(value)) {
    if (!arrayType) throw new Error(`${setting.key}: array supplied for scalar setting`);
    values = value;
  } else if (arrayType) {
    if (setting.coType === 'coStrings') {
      // This editor supplies Orca's semicolon-delimited point vector as text.
      // Keep the terminal empty element; it is part of the emitted cardinality.
      values = setting.key === 'small_area_infill_flow_compensation_model'
        ? String(value).split(';') : [value];
    } else {
      values = String(value).split(',');
    }
  } else {
    values = [value];
  }
  return JSON.stringify(values.map(item => atom(item, setting)));
}

export function canonicalConfig(value: string, setting: SettingDefinition): string {
  if (setting.coType === 'coString') return canonical(decodeString(value), setting);
  if (setting.coType === 'coStrings') return canonical(decodeStrings(value), setting);
  return canonical(value, setting);
}

export function numericMutationStep(current: number, setting: SettingDefinition): number {
  if (!Number.isFinite(current)) throw new Error(`${setting.key}: editor value is not finite`);
  // Orca serializes floats to six significant digits.
  return setting.type === 'int' ? 1 : Math.max(0.01, 10 ** (Math.floor(Math.log10(Math.abs(current) || 1)) - 5));
}

export function assertChangedConfig(
  setting: SettingDefinition,
  requested: unknown,
  baseline: Map<string, string>,
  actual: Map<string, string>,
): void {
  if (!baseline.has(setting.key)) throw new Error(`${setting.key}: baseline CONFIG_BLOCK did not emit this key`);
  if (!actual.has(setting.key)) throw new Error(`${setting.key}: changed CONFIG_BLOCK dropped this key`);
  const expected = canonical(requested, setting);
  const before = canonicalConfig(baseline.get(setting.key)!, setting);
  const after = canonicalConfig(actual.get(setting.key)!, setting);
  if (expected === before) throw new Error(`${setting.key}: requested value did not change the resolved baseline`);
  if (after === before) throw new Error(`${setting.key}: effective value remained unchanged`);
  if (after !== expected) {
    throw new Error(`${setting.key}: emitted ${actual.get(setting.key)} does not match requested ${JSON.stringify(requested)}`);
  }
}

export function assertComplete(rows: CoverageRow[]): void {
  const expected = inventory().map(row => `${row.profile}.${row.key}`).sort();
  const actual = rows.map(row => `${row.profile}.${row.key}`).sort();
  if (JSON.stringify(expected) !== JSON.stringify(actual)) throw new Error('Coverage inventory differs from the current UI registry');
  for (const row of rows.filter(row => row.status === 'config-verified')) {
    if (!row.attempted || !row.gcodeGenerated || !row.jobId || row.requested === undefined
      || row.baseline === undefined || row.emitted === undefined) {
      throw new Error(`${row.profile}.${row.key}: verified status has no complete fresh-job evidence`);
    }
    assertChangedConfig(definition(row.profile, row.key), row.requested,
      new Map([[row.key, row.baseline]]), new Map([[row.key, row.emitted]]));
  }
  const unresolved = rows.filter(row => row.status === 'unresolved');
  if (unresolved.length) throw new Error(`${unresolved.length} settings unresolved: ${unresolved.map(row => `${row.profile}.${row.key}`).join(', ')}`);
}

export function extrusionPlanes(gcode: string): number[] {
  const start = gcode.indexOf('; Z_HEIGHT:');
  if (start < 0) throw new Error('No layer toolpath marker');
  let z: number | undefined;
  const planes = new Set<number>();
  for (const raw of gcode.slice(start).split(/\r?\n/)) {
    const line = raw.split(';')[0];
    if (!/^G[01]\s/.test(line)) continue;
    const height = /(?:^|\s)Z(-?(?:\d+(?:\.\d*)?|\.\d+))/.exec(line);
    if (height) z = Number(height[1]);
    if (z !== undefined && /(?:^|\s)[XY]-?\d/.test(line)
      && /(?:^|\s)E(?:\d+(?:\.\d*)?|\.\d+)/.test(line)) planes.add(z);
  }
  return [...planes].sort((a, b) => a - b);
}

/** Deliberately limited command evidence, not a physical printer simulation. */
export function heaterTargets(gcode: string): number[] {
  return [...gcode.matchAll(/^M10[49]\s+[^;\r\n]*?\bS(\d+(?:\.\d+)?)/gm)].map(match => Number(match[1]));
}

export function assertCommandEvidence(key: string, requested: unknown, gcode: string, baselineGcode?: string): boolean {
  const value = Number(Array.isArray(requested) ? requested[0] : requested);
  if (key === 'layer_height' || key === 'initial_layer_print_height') {
    const planes = extrusionPlanes(gcode);
    if (planes.length < 5) throw new Error(`${key}: insufficient actual extrusion planes`);
    const observed = key === 'layer_height' ? planes[2] - planes[1] : planes[0];
    if (Math.abs(observed - value) > 0.0001) {
      throw new Error(`${key}: actual extrusion-plane ${observed} does not match ${value}`);
    }
    return true;
  }
  if (['nozzle_temperature', 'nozzle_temperature_initial_layer'].includes(key)) {
    if (!baselineGcode || heaterTargets(baselineGcode).length === 0) throw new Error(`${key}: baseline heater commands are required`);
    if (heaterTargets(baselineGcode).includes(value)) throw new Error(`${key}: requested target already occurs in a baseline heating phase; attribution is ambiguous`);
    const targets = heaterTargets(gcode);
    if (!targets.includes(value)) throw new Error(`${key}: no actual heater command targets ${value}`);
    return true;
  }
  return false;
}
