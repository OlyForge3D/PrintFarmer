/**
 * Status of a maintenance alert
 */
export enum MaintenanceAlertStatus {
  Active = 0,
  Acknowledged = 1,
  Resolved = 2,
  Dismissed = 3
}

/**
 * Represents an active maintenance alert that requires attention.
 * Generated by the MaintenanceAlertEngine based on printer statistics and maintenance schedules.
 */
export interface MaintenanceAlert {
  id: string;
  printerId: string;
  maintenanceScheduleId: string;
  title: string;
  message: string;
  severity: number; // 1=Low, 2=Medium, 3=High, 4=Critical
  status: MaintenanceAlertStatus;
  printerHoursAtTrigger: number;
  hoursSinceLastMaintenance?: number | null;
  daysSinceLastMaintenance?: number | null;
  createdAt: string; // ISO 8601 datetime
  acknowledgedAt?: string | null;
  acknowledgedBy?: string | null;
  resolvedAt?: string | null;
  resolvedBy?: string | null;
  dismissedAt?: string | null;
  dismissedBy?: string | null;
  dismissalReason?: string | null;
  updatedAt: string;
  // Navigation properties (optional for API responses)
  printer?: Record<string, unknown>; // Printer entity reference
  maintenanceSchedule?: MaintenanceSchedule;
}

/**
 * Defines a maintenance task and its interval/threshold for a specific printer.
 * Can be model-specific (seeded for all printers of a model) or printer-specific (custom per printer).
 */
export interface MaintenanceSchedule {
  id: string;
  printerId?: string | null;
  printerModelId?: string | null;
  manufacturerId?: string | null;
  motionType?: number | null;
  taskName: string;
  description?: string | null;
  component?: string | null; // e.g., "Hotend", "Bed", "Belts", "Bearings", "Fans"
  intervalHours?: number | null; // Maintenance interval in print hours
  intervalDays?: number | null; // Maintenance interval in calendar days
  estimatedDurationMinutes?: number | null;
  priority: number; // 1=Low, 2=Medium, 3=High, 4=Critical
  isActive: boolean;
  isDefault: boolean; // Seeded for all printers of this model
  createdAt: string;
  updatedAt: string;
  // Navigation properties (optional)
  printer?: Record<string, unknown>;
  printerModel?: Record<string, unknown>;
}

/**
 * Records a completed maintenance activity on a printer.
 * Provides audit trail and history for maintenance operations.
 */
export interface MaintenanceLog {
  id: string;
  printerId: string;
  maintenanceScheduleId?: string | null;
  resolvedAlertId?: string | null;
  taskName: string;
  notes?: string | null;
  component?: string | null;
  performedBy?: string | null;
  performedAt: string; // ISO 8601 datetime
  durationMinutes?: number | null;
  partsReplaced?: string | null;
  cost?: number | null;
  printerHoursAtMaintenance?: number | null;
  createdAt: string;
  // Navigation properties (optional)
  printer?: Record<string, unknown>;
  maintenanceSchedule?: MaintenanceSchedule;
  resolvedAlert?: MaintenanceAlert;
}

/**
 * Stores cumulative statistics for a printer (external + internal prints).
 * One-to-one relationship with Printer.
 */
export interface PrinterStatistics {
  id: string;
  printerId: string;
  totalPrintHours: number; // Cumulative print time in hours
  totalJobsCompleted: number; // Total number of completed print jobs
  totalJobsFailed: number; // Total number of failed print jobs
  totalFilamentUsedGrams: number; // Total filament used in grams
  totalFilamentUsedMeters: number; // Total filament used in meters
  lastSyncTime: string; // ISO 8601 datetime - when stats were last updated
  createdAt: string;
  updatedAt: string;
}

/**
 * Fleet-wide printer statistics with maintenance projections.
 * Returned by GET /api/maintenance/statistics/fleet
 */
export interface FleetPrinterStatistics {
  printerId: string;
  printerName: string;
  manufacturerName?: string | null;
  modelName?: string | null;
  isOnline: boolean;
  inMaintenance: boolean;
  totalPrintHours: number;
  totalJobsCompleted: number;
  totalJobsFailed: number;
  totalFilamentUsedGrams: number;
  totalFilamentUsedMeters: number;
  lastSyncTime?: string | null;
  /** Days until next maintenance task is due (negative = overdue) */
  daysUntilNextMaintenance?: number | null;
  /** Name of the next maintenance task due */
  nextMaintenanceTask?: string | null;
}

