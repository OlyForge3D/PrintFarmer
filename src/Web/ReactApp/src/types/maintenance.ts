/**
 * Status of a maintenance alert.
 *
 * Values are strings, not numbers: the API registers a bare
 * `JsonStringEnumConverter` (see `ControllerStartup.cs`), so C# enums are
 * serialized as their PascalCase member names (`"Active"`, not `0`).
 * Declaring these numerically makes every `alert.status === ...` comparison
 * silently false, which renders alert lists permanently empty.
 */
export enum MaintenanceAlertStatus {
  Active = 'Active',
  Acknowledged = 'Acknowledged',
  Resolved = 'Resolved',
  Dismissed = 'Dismissed'
}

/**
 * Represents an active maintenance alert that requires attention.
 * Generated by the MaintenanceAlertEngine based on printer statistics and maintenance schedules.
 */
export interface MaintenanceAlert {
  id: string;
  printerId: string;
  /**
   * Optional physical toolhead scope (see issue #711/#719). When present the
   * alert applies to a single toolhead on the printer; when `null`/omitted the
   * alert is printer-wide, which preserves legacy records. MMU/AMS gates are
   * never a valid maintenance toolhead scope.
   */
  toolheadId?: string | null;
  printerMaintenanceScheduleId?: string | null;
  maintenanceTaskId?: string | null;
  title: string;
  message: string;
  severity: number; // 1=Low, 2=Medium, 3=High, 4=Critical
  status: MaintenanceAlertStatus;
  printerHoursAtTrigger: number;
  hoursSinceLastMaintenance?: number | null;
  daysSinceLastMaintenance?: number | null;
  createdAt: string; // ISO 8601 datetime
  acknowledgedAt?: string | null;
  acknowledgedBy?: string | null;
  resolvedAt?: string | null;
  resolvedBy?: string | null;
  dismissedAt?: string | null;
  dismissedBy?: string | null;
  dismissalReason?: string | null;
  updatedAt: string;
  // Navigation properties (optional for API responses)
  printer?: Record<string, unknown>; // Printer entity reference
  printerMaintenanceSchedule?: Record<string, unknown>;
  maintenanceTask?: Record<string, unknown>;
}

